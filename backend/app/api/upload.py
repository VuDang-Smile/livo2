def _sanitize_filename_component(value: str) -> str:
    """Sanitize input to a filename-safe component."""
    safe_value = re.sub(r"[^A-Za-z0-9._-]+", "_", value).strip("_")
    return safe_value or "map"


def _format_iso_with_tz(dt: datetime) -> str:
    """
    Return ISO8601 string with timezone info in UTC.

    Contract: all timestamps written to metadata are stored as UTC.
    """
    return isoformat_utc(ensure_utc(dt))


def _write_metadata_file(
    map_name: str,
    vehicle_name: str,
    vehicle_id: str,
    size_bytes: int,
    created_at: datetime,
    uploaded_at: datetime,
) -> Path:
    """Write metadata JSON file (key-value) to storage directory."""
    storage_service.ensure_storage_directories()
    # Ngắn gọn: metadata_map (không kèm timestamp)
    filename = "metadata_map.json"
    metadata_path = storage_service.storage_dir / filename

    data = {
        "map_name": map_name,
        "vehicle_name": vehicle_name,
        "vehicle_id": vehicle_id,
        "size_bytes": size_bytes,
        "size_mb": round(size_bytes / 1024 / 1024, 2),
        "created_at": _format_iso_with_tz(created_at),
        "uploaded_at": _format_iso_with_tz(uploaded_at),
    }

    metadata_path.write_text(json.dumps(data, ensure_ascii=False, indent=2), encoding="utf-8")
    logger.info(f"Metadata file created at {metadata_path}")
    return metadata_path


@router.post("/upload", response_model=UploadResponse)
async def upload_map(
    file: UploadFile = File(...),
    map_name: str = Form(...),
    vehicle_id: str = Form(...)
):
    """
    Upload zip file (map output from Livo).
    
    Extract ZIP file, validate floorplan files, save PCD and floorplan images/metadata.
    ZIP must contain floorplan files generated by GUI (bag_mapping_tab.py).
    """
    try:
        map_name = (map_name or "").strip()
        vehicle_id = (vehicle_id or "").strip()

        if not map_name:
            raise HTTPException(status_code=400, detail="map_name is required")
        if not vehicle_id:
            raise HTTPException(status_code=400, detail="vehicle_id is required")

        vehicle = await database_service.get_vehicle(vehicle_id)
        if not vehicle:
            raise HTTPException(status_code=404, detail="Vehicle not found")
        vehicle_name = vehicle.get("name") or "Unknown"

        # Validate file type
        if not file.filename.endswith('.zip'):
            raise HTTPException(status_code=400, detail="Only zip files are allowed")
        
        # Read file content
        file_content = await file.read()
        file_size = len(file_content)
        
        # Validate file size
        if file_size > settings.MAX_UPLOAD_SIZE:
            raise HTTPException(
                status_code=413,
                detail=f"File size exceeds maximum allowed size of {settings.MAX_UPLOAD_SIZE} bytes"
            )
        
        # Publish MQTT event: upload started
        mqtt_service.publish_map_event("map.upload.started", {
            "filename": file.filename,
            "size": file_size
        })
        
        # Check for old map and publish event if exists
        old_map = await database_service.get_current_map()
        if old_map and settings.SINGLE_VERSION_MODE:
            mqtt_service.publish_map_event("map.old.removed", {
                "previous_upload_id": old_map.get("upload_id"),
                "reason": "new_map_uploaded"
            })
        
        # Process upload (save file, extract to storage, and save metadata)
        logger.info("=" * 60)
        logger.info(f"📤 Processing upload: {file.filename} ({file_size / 1024 / 1024:.2f} MB)")
        logger.info("=" * 60)
        result = await map_processor.process_upload(file_content, file.filename)
        if not result:
            logger.error("❌ Upload processing failed - no result returned")
            raise HTTPException(
                status_code=500, 
                detail="Failed to process upload. Check server logs for details."
            )
        
        # Verify extraction was successful
        logger.info("🔍 Verifying storage extraction...")
        storage_paths = result.get("metadata", {}).get("storage_paths", {})
        if storage_paths:
            logger.info(f"✅ Verified: {len(storage_paths)} items extracted to storage")
            for key, path in storage_paths.items():
                logger.info(f"   - {key}: {path}")
        else:
            logger.warning("⚠️ No storage_paths in result metadata")
        
        logger.info("=" * 60)
        logger.info(f"✅ Upload and extraction completed successfully!")
        logger.info(f"   Upload ID: {result['upload_id']}")
        logger.info("=" * 60)
        
        # Publish MQTT events
        mqtt_service.publish_map_event("map.upload.completed", {
            "upload_id": result["upload_id"],
            "filename": result["filename"],
            "size": result["size"]
        })
        
        if old_map and settings.SINGLE_VERSION_MODE:
            mqtt_service.publish_map_event("map.replaced", {
                "new_upload_id": result["upload_id"],
                "previous_upload_id": old_map.get("upload_id")
            })

        # Create metadata txt file and persist extended metadata
        try:
            file_stat = Path(result["file_path"]).stat()
            # Interpret mtime as an absolute instant and convert to UTC-aware datetime.
            # Using tz=UTC ensures we don't accidentally treat a local naive datetime as UTC.
            created_at_local = datetime.fromtimestamp(file_stat.st_mtime, tz=timezone.utc)
        except Exception as stat_error:
            logger.warning(f"Could not read file timestamps: {stat_error}")
            created_at_local = now_utc()

        # Use canonical UTC for upload time
        uploaded_at_local = now_utc()
        metadata_json_path = _write_metadata_file(
            map_name=map_name,
            vehicle_name=vehicle_name,
            vehicle_id=vehicle_id,
            size_bytes=result["size"],
            created_at=created_at_local,
            uploaded_at=uploaded_at_local,
        )

        extended_metadata = {
            "map_name": map_name,
            "vehicle_id": vehicle_id,
            "vehicle_name": vehicle_name,
            "metadata_json_path": str(metadata_json_path),
            "file_created_at": _format_iso_with_tz(created_at_local),
            "file_uploaded_at": _format_iso_with_tz(uploaded_at_local),
        }

        if "metadata" in result and isinstance(result["metadata"], dict):
            result["metadata"].update(extended_metadata)

        update_payload = {
            "metadata": result.get("metadata", {}),
            "map_name": map_name,
            "vehicle_id": vehicle_id,
            "vehicle_name": vehicle_name,
        }
        updated = await database_service.update_map(result["upload_id"], update_payload)
        if not updated:
            logger.warning("Failed to update map document with extended metadata")
        
        return UploadResponse(
            upload_id=UUID(result["upload_id"]),
            filename=result["filename"],
            status=result["status"],
            uploaded_at=result["uploaded_at"],
            size=result["size"],
            file_path=result["file_path"]
        )
    except HTTPException:
        raise
    except Exception as e:
        logger.error(f"Error uploading map: {e}")
        raise HTTPException(status_code=500, detail=str(e))


