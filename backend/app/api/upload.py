@router.delete("/current")
async def delete_current_map():
    """Delete current map."""
    try:
        map_doc = await database_service.get_current_map()
        if not map_doc:
            raise HTTPException(status_code=404, detail="No map found")
        
        # Delete file
        if map_doc.get("file_path"):
            file_path = Path(map_doc["file_path"])
            storage_service.delete_file(file_path)
        
        # Delete processed files (images and metadata)
        metadata = map_doc.get("metadata", {})
        if metadata.get("image_paths"):
            for view_id, rel_path in metadata["image_paths"].items():
                image_path = storage_service.get_processed_path(rel_path)
                storage_service.delete_file(image_path)
        
        if metadata.get("metadata_path"):
            metadata_path = storage_service.get_processed_path(metadata["metadata_path"])
            storage_service.delete_file(metadata_path)
        
        # Delete PCD file
        if metadata.get("pcd_path"):
            pcd_path = Path(metadata["pcd_path"])
            storage_service.delete_file(pcd_path)
        
        # Cleanup storage directory
        storage_service.cleanup_storage()
        
        # Delete from database
        success = await database_service.delete_current_map()
        if not success:
            raise HTTPException(status_code=500, detail="Failed to delete map")
        
        return {"success": True, "message": "Map deleted successfully"}
    except HTTPException:
        raise
    except Exception as e:
        logger.error(f"Error deleting current map: {e}")
        raise HTTPException(status_code=500, detail=str(e))


